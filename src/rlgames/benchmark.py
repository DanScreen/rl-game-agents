"""Benchmark results store and the generated leaderboard.

Every ``rlg bench`` / ``rlg chess-bench`` call appends one JSON line per agent to
``benchmarks/results.jsonl``; ``benchmarks/LEADERBOARD.md`` is regenerated from it,
keeping the latest result for each (game, agent) pair.
"""

from __future__ import annotations

import json
import time
from pathlib import Path
from typing import Any

RESULTS = Path("benchmarks/results.jsonl")
LEADERBOARD = Path("benchmarks/LEADERBOARD.md")


def record_result(entry: dict[str, Any], results_path: Path = RESULTS, leaderboard_path: Path = LEADERBOARD) -> None:
    results_path.parent.mkdir(parents=True, exist_ok=True)
    entry = {"timestamp": time.strftime("%Y-%m-%d %H:%M:%S"), **entry}
    with open(results_path, "a") as f:
        f.write(json.dumps(entry) + "\n")
    write_leaderboard(results_path, leaderboard_path)


def load_results(results_path: Path = RESULTS) -> list[dict[str, Any]]:
    if not results_path.exists():
        return []
    with open(results_path) as f:
        return [json.loads(line) for line in f if line.strip()]


def write_leaderboard(results_path: Path = RESULTS, leaderboard_path: Path = LEADERBOARD) -> None:
    latest: dict[tuple[str, str], dict[str, Any]] = {}
    for r in load_results(results_path):
        latest[(r["game"], r["agent"])] = r

    lines = [
        "# Leaderboard",
        "",
        "Generated by `rlg bench` / `rlg chess-bench` from `benchmarks/results.jsonl` "
        "(latest result per agent). Do not edit by hand.",
        "",
    ]
    games = sorted({g for g, _ in latest})
    for game in games:
        rows = [r for (g, _), r in latest.items() if g == game]
        lines += [f"## {game}", ""]
        if game == "chess":
            # chess results are per (agent, opponent) pair, not per agent
            lines += ["| Agent | Opponent | Games | W / D / L | Score | Elo diff | Date |", "|---|---|---|---|---|---|---|"]
            for r in _chess_rows(results_path):
                lines.append(
                    f"| {r['agent']} | {r['opponent']} | {r['games']} | {r['wins']} / {r['draws']} / {r['losses']} "
                    f"| {r['score']:.1%} | {r['elo_diff']:+.0f} | {r['timestamp'][:10]} |"
                )
        else:
            lines += ["| Agent | Episodes | Mean score | Std | Median | Min | Max | Train steps | Date |",
                      "|---|---|---|---|---|---|---|---|---|"]
            for r in sorted(rows, key=lambda r: -r["mean_return"]):
                lines.append(
                    f"| {r['agent']} | {r['episodes']} | {r['mean_return']:.1f} | {r['std_return']:.1f} "
                    f"| {r['median_return']:.1f} | {r['min_return']:.0f} | {r['max_return']:.0f} "
                    f"| {r.get('train_steps', '-')} | {r['timestamp'][:10]} |"
                )
        lines.append("")
    leaderboard_path.parent.mkdir(parents=True, exist_ok=True)
    leaderboard_path.write_text("\n".join(lines))


def _chess_rows(results_path: Path) -> list[dict[str, Any]]:
    latest: dict[tuple[str, str], dict[str, Any]] = {}
    for r in load_results(results_path):
        if r["game"] == "chess":
            latest[(r["agent"], r["opponent"])] = r
    return [latest[k] for k in sorted(latest)]
